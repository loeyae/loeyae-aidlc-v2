import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { classifyRepair, repairGuidance, sensorRepairDiagnostics, stableRepairMessage } from "../core/tools/aidlc-repair-guidance";
import { bindSession, claimToken } from "../core/tools/aidlc-session";
import { createInitialState, GLOBAL_WORKFLOW } from "../core/tools/aidlc-light-state";
import { saveFixtureState } from "./mars243_fixture_session";

const root = mkdtempSync(join(tmpdir(), "aidlc-repair-actions-"));
const originalBinding = process.env.AIDLC_SESSION_BINDING;
const put = (path: string, value: string | object) => { mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), typeof value === "string" ? value : JSON.stringify(value)); };
const instance = "code-generation@module:project@unit:default";
try {
  const state = createInitialState("express", "4.26.0", undefined, [], "targeted repair regression");
  Object.assign(state, { current_stage: "code-generation", current_stage_instance: instance, current_module: "project", current_unit: "default" });
  saveFixtureState(root, state);
  process.env.AIDLC_SESSION_BINDING = JSON.stringify(bindSession(root, { instance, owner: "fixture", session: "repair-actions", expected: claimToken(undefined) }).binding);
  const context = { stage_instance: instance, completed_stage_instances: ["tdd@module:project@unit:default"] };
  const missing = "RED evidence is missing and no approved historical-omission record exists";
  assert.equal(classifyRepair(missing).category, "approval-required");
  assert.equal(classifyRepair("RED_OMISSION_INVALID: GREEN sha256 changed; explicit renewed approval is required").category, "approval-required");
  const approval = sensorRepairDiagnostics([{ sensor: "test-quality", message: missing }], context)[0];
  assert.equal(approval.requires_human_approval, true);
  assert.equal(approval.sensor, "red-test-evidence");
  assert.equal(approval.stage_instance, "tdd@module:project@unit:default");
  assert(approval.command?.includes("--historical-omission"));
  assert(!approval.command?.includes("--all-sensors"));
  const stale = sensorRepairDiagnostics([{ sensor: "traceability-matrix", message: "evidence scope_digest changed" }], { ...context, completed_stage_instances: [instance] })[0];
  assert.equal(stale.action, "refresh-evidence");
  assert.deepEqual(stale.command, ["loeyae-aidlc", "evidence", "run", "--stage", "code-generation", "--module", "project", "--unit", "default", "--sensor", "traceability-matrix", "--refresh"]);
  const active = sensorRepairDiagnostics([{ sensor: "traceability-matrix", message: "evidence is invalid" }], context)[0];
  assert(!active.command?.includes("--refresh"), "active stages use ordinary targeted production");
  const historical = sensorRepairDiagnostics([{ sensor: "test-quality", message: "Evidence rejected at .aidlc/evidence/tdd/project/default/red-test-evidence.json: PHASE_INPUT_BINDING_CHANGED" }], context)[0];
  assert.equal(historical.sensor, "red-test-evidence");
  assert.equal(historical.action, "inspect");
  assert.equal(historical.command, undefined, "historical input drift cannot trigger a blind RED rerun");
  const moduleFailure = sensorRepairDiagnostics([{ sensor: "test-quality", message: "Evidence rejected at .aidlc/evidence/test-case-derivation/project/test-case-derivation.json: evidence scope_digest changed" }], context)[0];
  assert.equal(moduleFailure.stage_instance, "test-case-derivation@module:project", "module evidence cannot inherit a caller's unit axis");
  assert(!moduleFailure.command?.includes("--unit"));
  const projectArtifact = ".aidlc/evidence/build-and-test-templates/template-completeness.json";
  const projectMessage = `Evidence rejected at ${projectArtifact}: source_revision.scope_digest changed`;
  const projectFailure = sensorRepairDiagnostics([{ sensor: "test-quality", message: projectMessage }], context)[0];
  assert.equal(projectFailure.artifact, projectArtifact, "project-axis evidence paths must be recognized");
  assert.equal(projectFailure.stage_instance, "build-and-test-templates", "project evidence cannot inherit the consumer's module/unit");
  assert.deepEqual(projectFailure.command, ["loeyae-aidlc", "evidence", "run", "--stage", "build-and-test-templates", "--sensor", "template-completeness"]);
  const windowsFailure = sensorRepairDiagnostics([{ sensor: "test-quality", message: projectMessage.replaceAll("/", "\\") }], context)[0];
  assert.equal(windowsFailure.artifact, projectArtifact, "Windows evidence paths normalize to the same artifact");
  assert.deepEqual(windowsFailure.command, projectFailure.command);
  const prerequisite = sensorRepairDiagnostics([{ sensor: "document-slice-consistency", stage_instance: "units-generation@module:project", message: "SLICE_MANIFEST_STALE" }], context)[0];
  assert.equal(prerequisite.stage_instance, "units-generation@module:project", "a rechecked prerequisite retains its own target");
  assert(!prerequisite.command?.includes("--unit"));
  assert.equal(stableRepairMessage("automatic repair (a,b): Evidence producer blocked: Semantic checker blocked: PHASE_INPUT_BINDING_CHANGED"), stableRepairMessage("automatic repair (b): Evidence producer blocked: Semantic checker blocked: PHASE_INPUT_BINDING_CHANGED"));
  console.log("PASS typed repair diagnostics distinguish approvals, targeted refresh and historical observations");

  put("tests/behavior.ts", "original test input\n");
  put(".aidlc/evidence/code-generation/project/default/green-test-evidence.json", { phase_input_binding: { files: [{ path: "tests/behavior.ts" }] } });
  const stateBefore = readFileSync(join(root, "aidlc/active/aidlc-state.md"), "utf8");
  const message = (duration: string, timestamp: string) => `automatic semantic evidence production failed: [aidlc] evidence test-quality: waiting for semantic checker subprocess; elapsed=${duration}s; last_progress=${timestamp}\nPHASE_INPUT_BINDING_CHANGED`;
  const first = repairGuidance(root, GLOBAL_WORKFLOW, message("0.001", "2026-11-07T10:00:00.000Z"));
  const second = repairGuidance(root, GLOBAL_WORKFLOW, message("0.002", "2026-11-07T10:00:01.000Z"));
  assert.equal(first.persistence, "recorded");
  assert.equal(first.fingerprint, second.fingerprint);
  assert.equal(second.unchanged_attempts, 2);
  assert.equal(second.action, "diagnose");
  assert.equal(second.equivalent_retry_allowed, false);
  const journal = join(root, ".aidlc/continuation", readdirSync(join(root, ".aidlc/continuation"))[0]);
  const journalBefore = readFileSync(journal, "utf8");
  repairGuidance(root, GLOBAL_WORKFLOW, message("3.1", "2026-11-07T10:00:02.000Z"), true);
  assert.equal(readFileSync(journal, "utf8"), journalBefore, "preview cannot alter retry journals");
  put("tests/behavior.ts", "repaired test input\n");
  const repaired = repairGuidance(root, GLOBAL_WORKFLOW, message("0.003", "2026-11-07T10:00:03.000Z"));
  assert.notEqual(repaired.fingerprint, second.fingerprint);
  assert.equal(repaired.unchanged_attempts, 1);
  const changedFailure = repairGuidance(root, GLOBAL_WORKFLOW, "tests_failed must be 0");
  assert.notEqual(changedFailure.fingerprint, repaired.fingerprint);
  assert.equal(changedFailure.unchanged_attempts, 1);
  put(projectArtifact, { input: "original project observation" });
  const projectFirst = repairGuidance(root, GLOBAL_WORKFLOW, projectMessage, false, [projectFailure]);
  const projectRepeated = repairGuidance(root, GLOBAL_WORKFLOW, projectMessage, false, [projectFailure]);
  assert.equal(projectRepeated.unchanged_attempts, 2);
  put(projectArtifact, { input: "updated project observation" });
  const projectRepaired = repairGuidance(root, GLOBAL_WORKFLOW, projectMessage, false, [projectFailure]);
  assert.notEqual(projectRepaired.fingerprint, projectFirst.fingerprint, "changing a project prerequisite's evidence resets its diagnostic retry identity");
  assert.equal(projectRepaired.unchanged_attempts, 1);
  assert.equal(readFileSync(join(root, "aidlc/active/aidlc-state.md"), "utf8"), stateBefore);
  process.env.AIDLC_SESSION_BINDING = "invalid";
  const denied = repairGuidance(root, GLOBAL_WORKFLOW, "permission denied");
  assert.notEqual(denied.persistence, "recorded");
  console.log("PASS progress timing cannot reset retries; actual inputs and failures reset them; preview and invalid sessions cannot publish");
} finally {
  if (originalBinding === undefined) delete process.env.AIDLC_SESSION_BINDING; else process.env.AIDLC_SESSION_BINDING = originalBinding;
  rmSync(root, { recursive: true, force: true });
}
