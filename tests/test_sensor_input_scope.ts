import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, symlinkSync, statSync, utimesSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fixture, write } from "./mars244_fixture";
import { sensorInputs, sensorInputScope } from "../core/tools/aidlc-sensor-inputs";
import { readSourceRevision } from "../core/tools/aidlc-revision";
import { semanticCheckerIdentityErrors } from "../core/tools/aidlc-checker-identity";
const f = fixture("build-and-test-templates");
const sensor = "template-completeness", instance = "build-and-test-templates";
const template = "docs/aidlc/construction/build-and-test/build-instructions.md";
write(f.root, template, "# Build\nRun the complete real project build and inspect the output.\n");
write(f.root, "docs/aidlc/construction/build-and-test/unit-test-instructions.md", "# Tests\nRun the complete real project tests and inspect the output.\n");
const revision = () => readSourceRevision(f.root, sensorInputScope(f.root, sensor, instance)!);
const before = revision();
write(f.root, "src/shop/api/new.ts", "unrelated implementation\n");
const unrelated = revision();
assert.equal(unrelated.scope_digest, before.scope_digest);
assert.notEqual(unrelated.worktree_digest, before.worktree_digest, "full provenance remains available");
const stamp = statSync(join(f.root, template));
utimesSync(join(f.root, template), new Date(), new Date());
assert.equal(revision().scope_digest, before.scope_digest, "mtime is not semantic input");
write(f.root, template, "# Build\nRun the complete real project build and inspect the result.\n");
utimesSync(join(f.root, template), stamp.atime, stamp.mtime);
assert.notEqual(revision().scope_digest, before.scope_digest);
const sharedBefore = revision().scope_digest;
write(f.root, "shared/api.json", '{"revision":2}');
assert.notEqual(revision().scope_digest, sharedBefore, "shared declarations override narrow ownership");
assert(sensorInputs(f.root, sensor)!.files.some(file => file.path === "shared/api.json"));
assert(sensorInputs(f.root, sensor)!.files.some(file => file.path.endsWith("unit-manifest.json")));
assert.equal(sensorInputs(f.root, "unknown"), null);
assert.equal(sensorInputScope(f.root, "test-quality", "code-generation"), null);
assert(semanticCheckerIdentityErrors({ identity_version: 2, implementation_digest: "untrusted" }, "test-quality").length);
assert.throws(() => sensorInputs(f.root, sensor, "../escape", "u1"), /invalid template context/);
const target = mkdtempSync(join(tmpdir(), "aidlc-shared-input-"));
writeFileSync(join(target, "outside.json"), "{}");
symlinkSync(target, join(f.root, "linked-shared"), "junction");
write(f.root, "docs/aidlc/ideation/module-manifest.json", {schema_version:1, modules:[{module_id:"shop",name:"Shop",service_id:"shop",paths:["src/shop"],contract_paths:["linked-shared"]}]});
assert.throws(() => sensorInputs(f.root, sensor), /symlink/, "explicit dependencies cannot escape through links");
const large = mkdtempSync(join(tmpdir(), "aidlc-input-inventory-"));
mkdirSync(join(large, "shared"));
for (let i = 0; i < 2001; i++) writeFileSync(join(large, "shared", `${i}.json`), "{}");
write(large, "docs/aidlc/ideation/module-manifest.json", {schema_version:1,modules:[{module_id:"shop",name:"Shop",service_id:"shop",contract_paths:["shared"]}]});
assert.throws(() => sensorInputs(large, sensor), /inventory exceeds limit/, "large inventories fail instead of silently truncating");
console.log("PASS template dependency boundaries, byte hashes, full provenance, shared inputs, fallback and fail-closed paths");
