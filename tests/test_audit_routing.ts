import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { applyExecutionProfile, classifyExecutionProfile } from "../core/tools/aidlc-execution-profile";
import { fixture, write } from "./mars244_fixture";

const tool = pathToFileURL(resolve("core/tools/aidlc-orchestrate.ts")).href;
const f = fixture("application-design@module:shop");
process.chdir(f.root);
const { buildConditionContext, getExecutableStages, loadGraph, makeInstance } = await import(tool);
const graph = loadGraph();
const profile = applyExecutionProfile({ classified: classifyExecutionProfile({ scope: "bugfix", signals: new Set(["security_or_sensitive_data"]) }), at: new Date().toISOString() });
const selected = getExecutableStages(graph, "bugfix", [], profile).map((stage: { slug: string }) => stage.slug);
for (const slug of ["requirements-analysis", "application-design", "nfr-requirements", "nfr-design"]) assert(selected.includes(slug), slug);
const instance = makeInstance(graph.stages.find((stage: { slug: string }) => stage.slug === "application-design"), "module", { module_id: "shop" });
f.state.execution_profile = profile;
f.persist();
assert.equal(buildConditionContext(f.state, instance).has_nfr_needs, true, "security requires NFR even when unit stage declarations are empty");
write(f.root, `${f.base}/requirements.md`, "REQ-001 新接口，跨服务，敏感数据");
write(f.root, `${f.base}/workflow-plan.md`, "| application-design | skip | |\n");
assert.throws(() => buildConditionContext(f.state, instance), /skip requires/);
write(f.root, `${f.base}/workflow-plan.md`, "| application-design | skip | save time |\n");
assert.throws(() => buildConditionContext(f.state, instance), /skip conflicts/);
write(f.root, `${f.base}/requirements.md`, "REQ-001 局部修复，无新接口，不涉及跨服务");
assert.throws(() => buildConditionContext(f.state, instance), /skip conflicts/, "recorded security risk cannot be negated by a local skip");
delete f.state.execution_profile;
f.persist();
assert.equal(buildConditionContext(f.state, instance).has_application_design_needs, false);
console.log("PASS risk routing: security bugfix includes design, empty and conflicting skips reject, legitimate local skip retained");
